/**
 * Public Resource Face Registry (W6.1, bead 92x, Fable §6-§8).
 *
 * Diptych made real: one canonical registry defines every public resource kind,
 * its canonical agent markdown URL pattern, optional structured JSON URL pattern,
 * human-route key, and allowed suffixes.
 *
 * Strict Rule A1 / A4 / Rights Face Parity:
 * - Public resources expose license CC-BY-4.0 and policy metadata.
 * - Private, workshop, or moderation-detail kinds are strictly forbidden.
 * - Late producers (moves, review-queue, honors, stats) are labeled truthfully.
 */

