/** Look up a public resource entry by kind. */
export function getPublicResourceEntry(kind: PublicResourceKind): PublicResourceEntry | undefined {
  return PUBLIC_RESOURCE_REGISTRY.find((entry) => entry.kind === kind);
}

/** Check if a string is a valid public resource kind. */
export function isPublicResourceKind(kind: string): kind is PublicResourceKind {
  return (PUBLIC_RESOURCE_KINDS as readonly string[]).includes(kind);
}

/** Check if a string is a forbidden private / workshop / moderation kind. */
export function isForbiddenPrivateResource(kind: string): boolean {
  return (
    (FORBIDDEN_PRIVATE_KINDS as readonly string[]).includes(kind) ||
    kind.startsWith("workshop") ||
    kind.startsWith("screening") ||
    kind.includes("private")
  );
}

/** List all registered public resources. */
export function listPublicResources(): readonly PublicResourceEntry[] {
  return PUBLIC_RESOURCE_REGISTRY;
}
