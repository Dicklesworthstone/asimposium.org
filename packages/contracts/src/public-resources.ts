export const PublicResourceKindSchema = z.enum(PUBLIC_RESOURCE_KINDS);
export type PublicResourceKind = z.infer<typeof PublicResourceKindSchema>;

export const LateProducerSchema = z.enum(["moves", "review-queue", "honors", "stats"]);
export type LateProducer = z.infer<typeof LateProducerSchema>;

